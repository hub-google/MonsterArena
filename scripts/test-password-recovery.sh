#!/usr/bin/env bash
set -euo pipefail
root="$PWD"
work="$(mktemp -d)"
cd "$work"
supabase --version
supabase init --workdir "$work"
test -f "$work/supabase/config.toml" || { find "$work" -maxdepth 3 -type f; exit 1; }
cp "$root/supabase/templates/recovery.html" supabase/recovery.html
python3 - <<'PY'
from pathlib import Path
import re
p=Path("supabase/config.toml")
s=p.read_text()
s=re.sub(r'^site_url\s*=.*$', 'site_url = "http://127.0.0.1:4173/MonsterArena/"', s, flags=re.M)
s=re.sub(r'^additional_redirect_urls\s*=.*$', 'additional_redirect_urls = ["http://127.0.0.1:4173/MonsterArena/"]', s, flags=re.M)
s=re.sub(r'^enable_confirmations\s*=.*$', 'enable_confirmations = false', s, flags=re.M)
s+='\n[auth.email.template.recovery]\nsubject = "怪獸競技場 Monster Arena｜重設密碼"\ncontent_path = "./supabase/recovery.html"\n'
p.write_text(s)
PY
trap 'cd "$work"; supabase stop --no-backup >/dev/null 2>&1 || true; rm -rf "$work"' EXIT
supabase start --workdir "$work" -x studio,pg-meta,imgproxy,storage-api,realtime,edge-runtime,logflare,vector,supavisor
# Values are generated by the ephemeral local stack only.
eval "$(supabase status --workdir "$work" -o env)"
export VITE_SUPABASE_URL="$API_URL"
export VITE_SUPABASE_ANON_KEY="${PUBLISHABLE_KEY:-${ANON_KEY:-}}"
test "$VITE_SUPABASE_URL" = "http://127.0.0.1:54321"
test -n "$VITE_SUPABASE_ANON_KEY"
export MA_ISOLATED_AUTH_TEST=1
export PLAYWRIGHT_BASE_URL="http://127.0.0.1:4173/MonsterArena/"
cd "$root"
npm run dev -- --host 127.0.0.1 --port 4173 --strictPort > /tmp/ma-vite-auth.log 2>&1 &
for i in $(seq 1 30); do if curl -fsS "$PLAYWRIGHT_BASE_URL" >/dev/null; then break; fi; sleep 1; done
npx playwright test --config config/playwright.config.js password-recovery.spec.js
