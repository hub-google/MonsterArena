import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const sql=read('supabase/migrations/20261117_game_secure_core.sql');
const api=read('src/utils/api.js');
const arena=read('src/pages/Arena.jsx');
assert.match(sql,/p_action='battle'/);
assert.match(sql,/gen_random_uuid\(\)::text/);
assert.doesNotMatch(sql,/v_won\s*:=\s*\(p_data->>'won'\)/);
assert.match(sql,/drop policy if exists "Anyone can view profiles"/);
assert.match(sql,/revoke all on table public\.monsters/);
assert.match(sql,/rpc_hatch_egg/);
assert.match(sql,/v_value\s*:=\s*v_value\*1\.1/);
assert.doesNotMatch(api,/from\('monsters'\)\.update/);
assert.doesNotMatch(api,/from\('users'\)\.select\('user_id,username'\)/);
assert.match(api,/game_age_monsters/);
assert.match(api,/game_public_profiles/);
assert.match(arena,/api\.startBattle/);
assert.doesNotMatch(arena,/recordBattleResult/);
const guardrails=read('supabase/migrations/20261117_game_guardrails_perf.sql');
assert.match(guardrails,/p_action in \('feed','clean','train'\)/);
assert.match(guardrails,/arena_monsters_owner_idx/);
assert.match(guardrails,/arena_chat_channel_time_idx/);
const fairness=read('supabase/migrations/20261117_game_battle_fairness.sql');
assert.match(fairness,/if p_action in \('raid','battle'\)/);
assert.match(fairness,/created_at>clock_timestamp\(\)-interval '5 seconds'/);
assert.match(fairness,/arena_battle_recent_user_time_idx/);
const privacy=read('supabase/migrations/20261117_game_private_monsters.sql');
assert.match(privacy,/drop policy if exists "Anyone can view monsters"/);
assert.match(privacy,/game_plaza_monsters/);
assert.match(api,/game_plaza_monsters/);
assert.match(api,/legacyUsernameEmail/);
assert.match(api,/actualName.toLowerCase/);
const chips=read('supabase/migrations/20261117_game_chip_inventory.sql');
for (const item of ['chip_atk','chip_def','chip_hp','chip_spd']) {
  assert.ok(chips.includes(item),'missing chip type: '+item);
  assert.ok(api.includes('getInventory'),'game client must still load inventory');
}
assert.ok(chips.includes("item_type 1 or 6"),'legacy inventory support missing');
const bonusMigration=read('supabase/migrations/20261117_game_legacy_chip_preservation.sql');
assert.match(bonusMigration,/game_chip_reserves/);
assert.match(bonusMigration,/if v_old>5 then/);
assert.match(bonusMigration,/chip_slot_1_val=v_bonus/);
assert.match(bonusMigration,/chip_slot_2_val=v_bonus/);
console.log('Arena security and game contract checks passed.');
