import { test, expect } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';
import { randomUUID,randomBytes } from 'node:crypto';

test('real isolated Supabase Auth: recovery email, browser verification, refresh, update, old/new login', async ({ page }) => {
  test.skip(process.env.MA_ISOLATED_AUTH_TEST!=='1','Requires a dedicated local Supabase and Mailpit instance');
  test.setTimeout(90000);
  const url=process.env.VITE_SUPABASE_URL, key=process.env.VITE_SUPABASE_ANON_KEY;
  if(new URL(url).hostname!=='127.0.0.1'||new URL(url).port!=='54321')throw Error('Refusing to test any hosted project');
  const local=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
  const email='ma-recovery-'+randomUUID()+'@example.com';
  const oldPassword='Aa!'+randomBytes(16).toString('hex');
  const newPassword='Bb!'+randomBytes(16).toString('hex');
  const signup=await local.auth.signUp({email,password:oldPassword,options:{data:{username:'RecoveryFixture'}}});
  expect(signup.error?.message ?? null).toBeNull();
  expect(signup.data.session).toBeTruthy();
  const id=signup.data.user.id;
  await local.auth.signOut();
  await page.goto('./');
  await page.getByRole('button',{name:'忘記密碼？'}).click();
  await page.getByPlaceholder('輸入註冊 Email...').fill(email);
  await page.getByRole('button',{name:'寄送密碼重設信'}).click();
  await expect(page.getByRole('status')).toContainText('密碼重設信');
  let message;
  await expect.poll(async()=>{
    const response=await fetch('http://127.0.0.1:54324/api/v1/messages');
    const data=await response.json();
    const item=data.messages?.find(m=>m.To?.some(t=>t.Address===email));
    if(item)message=await (await fetch('http://127.0.0.1:54324/api/v1/message/'+item.ID)).json();
    return Boolean(message);
  },{timeout:20000}).toBe(true);
  expect(message.Subject).toContain('怪獸競技場');
  expect(message.HTML).toContain('MONSTER ARENA');
  const mailPage=await page.context().newPage();
  await mailPage.setContent(message.HTML);
  const href=await mailPage.getByRole('link',{name:'重設密碼',exact:true}).getAttribute('href');
  expect(new URL(href).hostname).toBe('127.0.0.1');
  await mailPage.close();
  await page.goto(href);
  await expect(page.getByRole('heading',{name:'重設密碼',exact:true})).toBeVisible();
  await expect(page.getByLabel('新密碼（至少 8 個字元）')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('新密碼（至少 8 個字元）')).toBeVisible();
  await page.getByLabel('新密碼（至少 8 個字元）').fill(newPassword);
  await page.getByLabel('再次輸入新密碼').fill(oldPassword);
  await page.getByRole('button',{name:'確認重設密碼'}).click();
  await expect(page.getByRole('alert')).toContainText('兩次輸入的密碼不一致');
  await page.getByLabel('再次輸入新密碼').fill(newPassword);
  await page.getByRole('button',{name:'確認重設密碼'}).click();
  await expect(page.getByRole('status')).toContainText('密碼已更新');
  await expect(page.getByRole('button',{name:'進入大廳'})).toBeVisible();
  const denied=await local.auth.signInWithPassword({email,password:oldPassword});
  expect(denied.error).toBeTruthy();
  const accepted=await local.auth.signInWithPassword({email,password:newPassword});
  expect(accepted.error?.message ?? null).toBeNull();
  expect(accepted.data.user.id).toBe(id);
  await local.auth.signOut();
  await page.goto(href);
  await expect(page.getByText('連結無效或已過期，請返回登入重新申請。')).toBeVisible();
  await expect(page.getByRole('button',{name:'確認重設密碼'})).toHaveCount(0);
});
